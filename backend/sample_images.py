"""Bundled sample images that the dashboard can load without an upload.

Clients address a sample by id only; the file path is resolved here from a fixed catalogue, so no client-supplied
path is ever opened. Descriptions state what each image is and what is not known about it.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

SAMPLES_DIR = Path(__file__).resolve().parent / "samples"


@dataclass(frozen=True)
class SampleImage:
    id: str
    filename: str
    label: str
    modality: str
    media_type: str
    description: str
    provenance: str
    licence: str
    caution: str

    def path(self) -> Path:
        return SAMPLES_DIR / self.filename

    def as_dict(self) -> dict:
        size = self.path().stat().st_size
        return {
            "id": self.id, "label": self.label, "modality": self.modality, "filename": self.filename, "media_type": self.media_type,
            "size_bytes": size, "description": self.description, "provenance": self.provenance, "licence": self.licence,
            "caution": self.caution, "file_url": f"/api/samples/{self.id}/file",
        }


SAMPLES: tuple[SampleImage, ...] = (
    SampleImage(
        "synthetic_ct", "synthetic_ct_scan.dcm", "Synthetic CT slice (DICOM)", "CT (fictional)", "application/dicom",
        "A fictional abdominal CT slice drawn by code, stored as a DICOM file with a modality rescale. It contains no patient data.",
        "Generated by backend/download_data.py in this repository.", "Generated for this project.",
        "Not a real scan: it shows how DICOM slices are read, not how real CT noise behaves.",
    ),
    SampleImage(
        "brain_mri", "brain_mri.png", "Brain MRI slice (PNG)", "MRI", "image/png",
        "Slice 5 of scikit-image's data.brain(), a 10-slice subset of the University of North Carolina Volume Rendering Test Data Set, "
        "exported as an 8-bit PNG.",
        "scikit-image sample data; the full data set is listed at https://graphics.stanford.edu/data/voldata/.",
        "Not verified: the terms of the original archive could not be checked. Use for demonstration only.",
        "An 8-bit export: original intensities and DICOM header are not available. MRI magnitude noise is not Gaussian (it is Rician), "
        "so the Gaussian noise added here is a teaching device, not a model of MRI noise.",
    ),
    SampleImage(
        "cell_phase", "cells_tissue.png", "Cell in saline (quantitative phase image)", "Quantitative phase microscopy", "image/png",
        "A single cell floating in saline, imaged by digital holography (scikit-image's data.cell()). It is a microscopy image, not tissue and not "
        "a radiological image.",
        "scikit-image sample data (qpformat; see the scikit-image documentation of data.cell).",
        "CC0 (public-domain dedication) according to the scikit-image documentation of data.cell.",
        "Has a banding artefact in the background. Included to show the filters on a non-radiological image.",
    ),
)

BY_ID = {sample.id: sample for sample in SAMPLES}


def available_samples() -> list[SampleImage]:
    """Catalogued samples whose file is present on this server."""
    return [sample for sample in SAMPLES if sample.path().is_file()]


def find_sample(sample_id: str) -> SampleImage | None:
    sample = BY_ID.get(sample_id)
    return sample if sample is not None and sample.path().is_file() else None
