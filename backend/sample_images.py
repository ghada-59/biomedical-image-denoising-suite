"""Bundled sample images that the dashboard can load without an upload.

Clients address a sample by id only; the file path is resolved here from a fixed catalogue, so no client-supplied
path is ever opened. Descriptions state what each image is and what is not known about it.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

SAMPLES_DIR = Path(__file__).resolve().parent / "samples"


@dataclass(frozen=True)
class SampleImage:
    id: str
    filename: str
    label: str
    modality: str
    media_type: str
    description: str
    provenance: str
    licence: str
    caution: str

    def path(self) -> Path:
        return SAMPLES_DIR / self.filename

    def as_dict(self) -> dict:
        size = self.path().stat().st_size
        return {
            "id": self.id, "label": self.label, "modality": self.modality, "filename": self.filename, "media_type": self.media_type,
            "size_bytes": size, "description": self.description, "provenance": self.provenance, "licence": self.licence,
            "caution": self.caution, "file_url": f"/api/samples/{self.id}/file",
        }


