BY_ID = {sample.id: sample for sample in SAMPLES}


def available_samples() -> list[SampleImage]:
    """Catalogued samples whose file is present on this server."""
    return [sample for sample in SAMPLES if sample.path().is_file()]


def find_sample(sample_id: str) -> SampleImage | None:
    sample = BY_ID.get(sample_id)
    return sample if sample is not None and sample.path().is_file() else None
